#!/usr/bin/env python3
"""Generates frontend/src/design/tokens.css from the DTCG token files (single source of truth).

Sources (frontend/src/design/tokens/):
    base.tokens.json    theme-independent tokens (radii)
    light|dark|warm.tokens.json   one file per theme; each top-level group becomes one blank-line
                        block in the CSS, and each leaf name IS the CSS custom property name
    contrast.json       foreground/background pairs checked by scripts/check_contrast.py

    python3 scripts/build_tokens.py           write tokens.css, then run the contrast check
    python3 scripts/build_tokens.py --check   fail if tokens.css is out of date or contrast fails

Never edit tokens.css by hand. Standard library only.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TOKENS_DIR = ROOT / "frontend" / "src" / "design" / "tokens"
OUT = ROOT / "frontend" / "src" / "design" / "tokens.css"
THEMES = ("light", "dark", "warm")

HEADER = """\
/*
 * GENERATED by scripts/build_tokens.py from src/design/tokens/*.tokens.json (DTCG).
 * Do not edit by hand: change the JSON, run `make tokens`, commit both. CI runs
 * `make tokens-check` and fails when this file is out of date.
 *
 * This is the ONLY place raw colors may appear in the frontend.
 * Components use the semantic Tailwind utilities generated from these
 * variables in ./index.css (bg-surface, text-fg, border-border, ...).
 *
 * Themes switch via <html data-theme="light|dark|warm">.
 * Brand values for --primary, --bg, --surface and --fg are fixed by
 * docs/ARCHITECTURE.md section 5.1. Every pair in tokens/contrast.json is
 * checked for WCAG AA by scripts/check_contrast.py and src/design/contrast.test.ts,
 * so a change here that breaks contrast fails `make tokens-check` and `pnpm test`.
 *
 * Token families (leaf name = CSS custom property name)
 *   surfaces      --bg --surface --surface-raised --subtle
 *   text          --fg --fg-muted
 *   lines         --border --border-strong --card-border --ring
 *   brand         --primary(-fg|-hover|-strong|-soft)
 *   neutral fills --secondary(-fg|-hover) --accent(-fg)
 *   status        --{success,warning,danger,info}: solid, -contrast (text on
 *                 solid), -bg (soft fill), -fg (text on soft fill or surface),
 *                 -border
 *   service line  --state-{requested,invoiced,paid,performed,cancelled,pending}
 *                 solid (dots/borders), -bg, -fg
 *   elevation     --elevation-card --elevation-raised --elevation-overlay --overlay
 *   shape         --card-radius --control-radius
 */
"""


def load_json(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def load_theme(theme: str) -> dict[str, Any]:
    return load_json(TOKENS_DIR / f"{theme}.tokens.json")


# ------------------------------------------------------------------ value formatting


def _num(value: float) -> str:
    return f"{value:g}"


def _px(dim: dict[str, Any]) -> str:
    if dim["unit"] != "px":
        raise ValueError(f"only px dimensions are supported: {dim}")
    v = dim["value"]
    return "0" if v == 0 else f"{_num(v)}px"


def _hex(value: dict[str, Any]) -> str:
    h = value["hex"].lower()
    if not re.fullmatch(r"#[0-9a-f]{6}", h):
        raise ValueError(f"bad hex: {h}")
    # The components are the DTCG-native form; they must agree with the hex we emit.
    rgb = [int(h[i : i + 2], 16) for i in (1, 3, 5)]
    for got, want in zip(value["components"], rgb, strict=True):
        if abs(got * 255 - want) > 0.6:
            raise ValueError(f"components do not match hex {h}: {value['components']}")
    return h


def css_color(value: dict[str, Any]) -> str:
    h = _hex(value)
    alpha = value.get("alpha", 1)
    if alpha == 1:
        return h
    r, g, b = (int(h[i : i + 2], 16) for i in (1, 3, 5))
    return f"rgb({r} {g} {b} / {_num(alpha)})"


def css_shadow(layers: list[dict[str, Any]]) -> str:
    if not layers:
        return "none"
    out = []
    for layer in layers:
        parts = [_px(layer["offsetX"]), _px(layer["offsetY"]), _px(layer["blur"])]
        if layer["spread"]["value"] != 0:
            parts.append(_px(layer["spread"]))
        parts.append(css_color(layer["color"]))
        out.append(" ".join(parts))
    return ", ".join(out)


def css_value(token: dict[str, Any], inherited: str | None) -> str:
    kind = token.get("$type", inherited)
    value = token["$value"]
    if kind == "color":
        return css_color(value)
    if kind == "shadow":
        return css_shadow(value)
    if kind == "dimension":
        return _px(value)
    raise ValueError(f"unsupported token type {kind!r}")


# ------------------------------------------------------------------ walking


def leaves(group: dict[str, Any], inherited: str | None = None):
    """Yield (name, token, type) for every leaf of a group, in file order."""
    kind = group.get("$type", inherited)
    for key, node in group.items():
        if key.startswith("$"):
            continue
        if "$value" in node:
            yield key, node, node.get("$type", kind)
        else:
            yield from leaves(node, kind)


def groups(doc: dict[str, Any]):
    for key, node in doc.items():
        if not key.startswith("$"):
            yield key, node


def resolved_hex(doc: dict[str, Any]) -> dict[str, str]:
    """name -> opaque #rrggbb for every color leaf (used by the contrast check)."""
    out: dict[str, str] = {}
    for _, group in groups(doc):
        for name, token, kind in leaves(group):
            if kind == "color":
                out[name] = _hex(token["$value"])
    return out


def _declarations(doc: dict[str, Any], scheme: str | None) -> list[str]:
    blocks: list[str] = []
    if scheme:
        blocks.append(f"  color-scheme: {scheme};")
    for _, group in groups(doc):
        lines = []
        seen: set[str] = set()
        for name, token, kind in leaves(group):
            if name in seen:
                raise ValueError(f"duplicate token {name}")
            seen.add(name)
            lines.append(f"  --{name}: {css_value(token, kind)};")
        blocks.append("\n".join(lines))
    return blocks


def render() -> str:
    parts = [HEADER]

    base = load_json(TOKENS_DIR / "base.tokens.json")
    parts.append(":root {\n" + "\n".join(_declarations(base, None)) + "\n}\n")

    names_by_theme: dict[str, set[str]] = {}
    for theme in THEMES:
        doc = load_theme(theme)
        ext = doc["$extensions"]["hospital-sys"]
        names_by_theme[theme] = {n for _, g in groups(doc) for n, _, _ in leaves(g)}
        banner = f"/* {'-' * (69 - len(theme))} {theme} */"
        decls = _declarations(doc, ext["colorScheme"])
        # First block is color-scheme alone, followed by a blank line before the groups.
        body = decls[0] + "\n\n" + "\n\n".join(decls[1:])
        parts.append(f"{banner}\n{ext['selector']} {{\n{body}\n}}\n")

    ref = names_by_theme[THEMES[0]]
    for theme in THEMES[1:]:
        if names_by_theme[theme] != ref:
            diff = sorted(names_by_theme[theme] ^ ref)
            raise ValueError(f"theme {theme} defines different tokens than {THEMES[0]}: {diff}")

    return "\n".join(parts)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    css = render()
    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != css:
            print(
                f"tokens: {OUT.relative_to(ROOT)} is out of date with the token JSON; run `make tokens` and commit",
                file=sys.stderr,
            )
            return 1
        print("tokens: tokens.css is up to date")
    else:
        OUT.write_text(css, encoding="utf-8")
        print(f"tokens: wrote {OUT.relative_to(ROOT)}")

    from check_contrast import main as contrast_main

    return contrast_main()


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    sys.exit(main(sys.argv[1:]))
